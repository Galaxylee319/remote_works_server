def _sync_source_roots() -> List[str]:
    """Real paths of configured external sync directories."""
    roots = []
    for src in config.get("sync_dirs", {}).values():
        real = os.path.realpath(src)
        if os.path.isdir(real):
            roots.append(real)
    return roots


def _is_within(path: str, root: str) -> bool:
    return path == root or path.startswith(root + os.sep)


def _is_allowed_symlink_dir(full: str, root_dir: str) -> bool:
    """Only follow symlinks that point into the root or a configured sync dir."""
    if not os.path.islink(full):
        return True
    real = os.path.realpath(full)
    allowed = [os.path.realpath(root_dir)] + _sync_source_roots()
    return any(_is_within(real, r) for r in allowed)


def resolve_safe_path(root_dir: str, request_path: str) -> Tuple[Optional[str], Optional[str]]:
    """Resolve ``request_path`` against ``root_dir``.

    Returns ``(abs_path, None)`` on success or ``(None, error_message)`` on
    failure. Symlinks are checked with ``realpath``: only links that stay inside
    the root or point into a configured ``sync_dirs`` source are allowed.
    """
    if request_path is None:
        request_path = ""
    try:
        clean = str(request_path).lstrip("/")
        if "\x00" in clean:
            return None, "非法路径"
        abs_path = os.path.abspath(os.path.join(root_dir, clean))
        abs_real = os.path.realpath(abs_path)
    except (ValueError, OSError):
        return None, "路径解析失败"

    root_abs = os.path.abspath(root_dir)
    root_real = os.path.realpath(root_dir)

    # Keep the *logical* path inside the served root so links generated by the UI
    # stay as /browse/<alias>/... and don't leak real filesystem locations.
    if abs_path != root_abs and not abs_path.startswith(root_abs + os.sep):
        return None, "路径超出允许目录"

    allowed_real = [root_real] + _sync_source_roots()
    if not any(_is_within(abs_real, r) for r in allowed_real):
        return None, "路径超出允许目录"
    if not os.path.exists(abs_real):
        return None, "路径不存在"
    return abs_path, None


def _is_hidden(name: str) -> bool:
    return name.startswith(".")


def _matches_any(name: str, patterns: List[str]) -> bool:
    for pattern in patterns:
        if fnmatch.fnmatch(name, pattern):
            return True
    return False


